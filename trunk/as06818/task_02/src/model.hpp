#ifndef TASK02_AS06818_MODEL_HPP
#define TASK02_AS06818_MODEL_HPP

// Абстрактная математическая модель объекта управления.
// Конкретные уравнения реализуются классами-наследниками,
// поэтому расчёт шага и сброс состояния — чисто виртуальные методы.
class Model {
public:
    virtual ~Model() = default;

    // Расчёт следующего состояния по входному воздействию u.
    virtual double step(double u) = 0;

    // Возврат внутреннего состояния к начальному значению.
    virtual void reset() = 0;
};

#endif
