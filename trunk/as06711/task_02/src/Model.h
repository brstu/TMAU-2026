#pragma once
#include <vector>

// Абстрактный базовый класс для всех моделей варианта 19.
class Model {
public:
    virtual ~Model() = default;

    // Один шаг моделирования: получить вход u, вернуть новое значение y
    virtual double step(double u) = 0;

    // Привести внутреннее состояние к начальному (нулевому)
    virtual void reset() = 0;

    // Человекочитаемое имя модели
    virtual const char* name() const = 0;

    // Необязательная установка начальных значений
    virtual void setInitialState(const std::vector<double>& /*init*/) {
        // Метод намеренно оставлен пустым, так как установка начального
        // состояния является опциональной. По умолчанию модели 
        // инициализируются нулями в своих конструкторах.
    }
};